/**
 * MCP tools — Árajánlatok (price proposals).
 *
 * Domain: proposals
 * Endpoints:
 *   GET  /api/proposals
 *   POST /api/proposals/approve
 *   POST /api/proposals/reject
 *   POST /api/proposals/rollback
 */
import { randomUUID } from 'node:crypto'
import { z } from 'zod'
import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js'
import type { HasznoClient } from '../client/index.js'
import { HasznoApiError, ShopTokenNotSupportedError } from '../client/index.js'

// ── helpers ──────────────────────────────────────────────────────────────────

function ok(data: unknown): { content: [{ type: 'text'; text: string }] } {
  return { content: [{ type: 'text' as const, text: JSON.stringify(data, null, 2) }] }
}

function err(msg: string): { content: [{ type: 'text'; text: string }]; isError: true } {
  return { isError: true, content: [{ type: 'text' as const, text: msg }] }
}

function requireConfirm(confirm: boolean | undefined): ReturnType<typeof err> | null {
  if (!confirm) {
    return err(
      'Safety gate: this tool modifies data. ' +
        'Re-call with confirm: true to proceed. ' +
        'Read the tool description and verify the input before confirming.',
    )
  }
  return null
}

function handleApiError(e: unknown, action: string): ReturnType<typeof err> {
  if (e instanceof ShopTokenNotSupportedError) {
    return err(e.message)
  }
  if (e instanceof HasznoApiError) {
    return err(`API error during ${action}: ${e.message} (status ${e.status})`)
  }
  return err(`Unexpected error during ${action}: ${String(e)}`)
}

// ── registration ─────────────────────────────────────────────────────────────

export function registerProposalsTools(server: McpServer, client: HasznoClient): void {
  // ── haszno_proposals_list ──────────────────────────────────────────────────
  server.tool(
    'haszno_proposals_list',
    `List price-change proposals generated by Haszno rules.

A "proposal" is a recommended price change that the shop owner must review
before it takes effect.  Each proposal has:
  • oldPriceGross / proposedPriceGross — current and suggested prices (HUF gross)
  • reason — why the change was suggested (e.g. "market undercut detected")
  • source — which rule or trigger created it
  • status — pending | approved | rejected | rolled_back
  • batchId — groups proposals applied together (use for rollback)

Use this tool to review pending proposals before calling approve/reject,
or to audit previously approved/rejected ones.

Returns up to \`limit\` proposals (default 25, max 100) starting at \`offset\`.
Includes a \`_meta\` field with total count hint and pagination cursor.`,
    {
      status: z
        .enum(['pending', 'approved', 'rejected', 'rolled_back'])
        .optional()
        .describe(
          'Filter by status. Omit to return all statuses. ' +
            '"pending" is the most useful — these need a decision.',
        ),
      productId: z
        .number()
        .int()
        .positive()
        .optional()
        .describe('Narrow to a single product ID.'),
      limit: z
        .number()
        .int()
        .min(1)
        .max(100)
        .default(25)
        .describe('Maximum number of proposals to return (1–100, default 25).'),
      offset: z
        .number()
        .int()
        .min(0)
        .default(0)
        .describe('Skip this many proposals (for pagination). Default 0.'),
    },
    { readOnlyHint: true },
    async (args) => {
      try {
        const all = await client.proposals.list(
          args.status ? { status: args.status } : undefined,
        )

        const filtered =
          args.productId != null
            ? all.filter((p) => p.productId === args.productId)
            : all

        const page = filtered.slice(args.offset, args.offset + args.limit)

        return ok({
          _meta: {
            total: filtered.length,
            offset: args.offset,
            limit: args.limit,
            hasMore: args.offset + args.limit < filtered.length,
          },
          proposals: page.map((p) => ({
            id: p.id,
            productId: p.productId,
            productName: p.productName,
            productSku: p.productSku,
            oldPriceGross: p.oldPriceGross,
            proposedPriceGross: p.proposedPriceGross,
            diffGross: p.proposedPriceGross - p.oldPriceGross,
            reason: p.reason,
            source: p.source,
            status: p.status,
            batchId: p.batchId,
            createdAt: p.createdAt,
            decidedAt: p.decidedAt,
          })),
        })
      } catch (e) {
        return handleApiError(e, 'haszno_proposals_list')
      }
    },
  )

  // ── haszno_proposals_market ────────────────────────────────────────────────
  server.tool(
    'haszno_proposals_market',
    `Show pending proposals for a product together with the product's market context.

Use this before approving or rejecting to understand whether the proposed
price makes sense given the current market situation.

Returns:
  • product — name, SKU, costNet (HUF net), current price/margin, AI-recommended
    price/margin, cheapest market competitor (marketMinGross, marketShop)
  • pendingProposals — proposals with status "pending" for this product, ordered
    by creation time (newest first)

All prices are in HUF.  "gross" = VAT-inclusive, "net" = VAT-exclusive.
Margin percentages are calculated on the net sale price after VAT.`,
    {
      productId: z
        .number()
        .int()
        .positive()
        .describe('The product ID to inspect. Obtain from haszno_proposals_list.'),
    },
    { readOnlyHint: true },
    async (args) => {
      try {
        const [products, proposals] = await Promise.all([
          client.products.list(),
          client.proposals.list({ status: 'pending' }),
        ])

        const product = products.find((p) => p.id === args.productId)
        if (!product) {
          return err(
            `Product ${args.productId} not found. ` +
              'Use haszno_proposals_list to see valid product IDs.',
          )
        }

        const pending = proposals
          .filter((p) => p.productId === args.productId)
          .sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime())

        return ok({
          product: {
            id: product.id,
            sku: product.sku,
            name: product.name,
            supplierName: product.supplierName,
            costNet: product.costNet,
            stock: product.stock,
            listed: product.listed,
            current: {
              priceGross: product.priceGross,
              marginNet: product.current.marginNet,
              marginPct: product.current.marginPct,
            },
            recommended: {
              priceGross: product.recommended.priceGross,
              marginNet: product.recommended.marginNet,
              marginPct: product.recommended.marginPct,
            },
            market: {
              minGross: product.marketMinGross,
              shop: product.marketShop,
            },
            rrpGross: product.rrpGross,
          },
          pendingProposals: pending.map((p) => ({
            id: p.id,
            oldPriceGross: p.oldPriceGross,
            proposedPriceGross: p.proposedPriceGross,
            diffGross: p.proposedPriceGross - p.oldPriceGross,
            reason: p.reason,
            source: p.source,
            batchId: p.batchId,
            createdAt: p.createdAt,
          })),
        })
      } catch (e) {
        return handleApiError(e, 'haszno_proposals_market')
      }
    },
  )

  // ── haszno_proposals_approve ───────────────────────────────────────────────
  server.tool(
    'haszno_proposals_approve',
    `Approve price-change proposals and apply them immediately to the shop.

**WRITE operation — requires confirm: true.**

**NOT available with a shop API token (haszno_).** Bearer tokens are permanently
blocked from approval operations (the server returns 403 with
"Az ügynök-token nem hagyhat jóvá árjavaslatokat"). Approval requires a human
session. Use the Haszno web app at https://haszno.com/app/javaslatok instead.
This tool works with legacy key (x-api-key) and HTTP Basic credentials.

If \`ids\` is provided: approve only those proposal IDs.
If \`ids\` is omitted: approve ALL pending proposals (batch-approve).

On success returns:
  • batchId — ID of the approval batch (save this — you can roll it back with
    haszno_proposals_rollback if the prices turn out to be wrong)
  • applied — number of proposals actually applied

Workflow:
  1. Call haszno_proposals_list with status:"pending" to see what is pending.
  2. Optionally call haszno_proposals_market per product to check context.
  3. Call this tool with the IDs you want to approve (or no IDs for all).
  4. Save the returned batchId in case you need to roll back.`,
    {
      ids: z
        .array(z.number().int().positive())
        .optional()
        .describe(
          'Proposal IDs to approve. ' +
            'Omit to approve all pending proposals (use with care).',
        ),
      confirm: z
        .boolean()
        .describe('Must be true to proceed. Safety gate — prevents accidental writes.'),
    },
    { destructiveHint: false, idempotentHint: false },
    async (args) => {
      const gate = requireConfirm(args.confirm)
      if (gate) return gate

      try {
        const result = await client.proposals.approve(
          args.ids ? { ids: args.ids } : undefined,
        )
        return ok({
          batchId: result.batchId,
          applied: result.applied,
          note:
            result.batchId
              ? `Prices updated. Use batchId "${result.batchId}" with haszno_proposals_rollback to undo.`
              : 'No proposals were applied (none were pending).',
        })
      } catch (e) {
        return handleApiError(e, 'haszno_proposals_approve')
      }
    },
  )

  // ── haszno_proposals_reject ────────────────────────────────────────────────
  server.tool(
    'haszno_proposals_reject',
    `Reject price-change proposals so they will not be applied.

**WRITE operation — requires confirm: true.**

**NOT available with a shop API token (haszno_).** Bearer tokens are permanently
blocked from rejection operations. Use the Haszno web app at
https://haszno.com/app/javaslatok instead.
This tool works with legacy key (x-api-key) and HTTP Basic credentials.

Rejected proposals are kept in history (status becomes "rejected") so you can
audit why a proposal was not applied.  Rejecting does NOT change any prices.

Provide the \`ids\` of the proposals to reject.  Use haszno_proposals_list
with status:"pending" to get the IDs.

Returns:
  • rejected — number of proposals marked as rejected`,
    {
      ids: z
        .array(z.number().int().positive())
        .min(1)
        .describe('IDs of the proposals to reject. At least one is required.'),
      confirm: z
        .boolean()
        .describe('Must be true to proceed. Safety gate — prevents accidental writes.'),
    },
    { destructiveHint: false, idempotentHint: true },
    async (args) => {
      const gate = requireConfirm(args.confirm)
      if (gate) return gate

      try {
        const result = await client.proposals.reject({ ids: args.ids })
        return ok({
          rejected: result.rejected,
          note: `${result.rejected} proposal(s) marked as rejected. No prices were changed.`,
        })
      } catch (e) {
        return handleApiError(e, 'haszno_proposals_reject')
      }
    },
  )

  // ── haszno_proposals_propose ──────────────────────────────────────────────
  server.tool(
    'haszno_proposals_propose',
    `Submit a price-change proposal for human review (shop API token only).

**Requires a shop API token** (starts with "haszno_") sent as Bearer.

Creates a PENDING proposal for the given product. The price is NEVER applied
automatically — a human must approve it via the Haszno web app.

Constraints:
  • proposedPriceGross must be ≥ the minimum-profit price floor (cost × (1+VAT)
    / (1−minMarginPct)). The server enforces this — a price below floor returns 422.
  • reason must be 1–500 characters of plain text. It is stored verbatim and
    shown to the shop owner — write clearly why the price change makes sense.
  • A nonce is generated automatically and reused on transport retries to prevent
    duplicate proposals. Do not call this tool twice for the same change.

Returns on success:
  • id — the new proposal's ID
  • status — always "pending"
  • createdAt — ISO timestamp

Error codes:
  • 401 — token invalid, expired, or revoked
  • 403 — token scope is "read"; needs "write"
  • 404 — product ID not found (or not in this shop)
  • 409 — duplicate nonce (previous submission succeeded)
  • 422 — proposed price is below the minimum-profit floor`,
    {
      productId: z
        .number()
        .int()
        .positive()
        .describe('ID of the product to propose a price change for.'),
      proposedPriceGross: z
        .number()
        .int()
        .positive()
        .describe(
          'Proposed gross price in HUF (whole forints, VAT-inclusive). ' +
            'Must be ≥ the price floor enforced by the server.',
        ),
      reason: z
        .string()
        .min(1)
        .max(500)
        .describe(
          'Plain-text explanation for the shop owner (1–500 characters). ' +
            'Example: "Piaci minimum 9 100 Ft; 1%-os alálövéssel versenyképes".',
        ),
    },
    { destructiveHint: false, idempotentHint: false },
    async (args) => {
      // Generate nonce once per tool invocation; retries within request() reuse the same body.
      const nonce = randomUUID()
      try {
        const result = await client.proposals.propose({
          productId: args.productId,
          proposedPriceGross: args.proposedPriceGross,
          reason: args.reason,
          nonce,
        })
        return ok({
          id: result.id,
          status: result.status,
          createdAt: result.createdAt,
          note:
            `Javaslat beküldve (ID: ${result.id}). ` +
            'Az ár nem változott — a bolt tulajdonosának jóvá kell hagynia a Haszno webalkalmazásban.',
        })
      } catch (e) {
        return handleApiError(e, 'haszno_proposals_propose')
      }
    },
  )

  // ── haszno_proposals_rollback ──────────────────────────────────────────────
  server.tool(
    'haszno_proposals_rollback',
    `Roll back all price changes from a previously approved batch.

**WRITE operation — requires confirm: true.**
**DESTRUCTIVE: restores prices to their pre-approval values.**

**NOT available with a shop API token (haszno_).** Bearer tokens are permanently
blocked from rollback operations. Use the Haszno web app at
https://haszno.com/app/javaslatok instead.
This tool works with legacy key (x-api-key) and HTTP Basic credentials.

Use this when an approval batch produced incorrect prices and you want to
undo the whole batch atomically.  You need the \`batchId\` returned by
haszno_proposals_approve.

Returns:
  • rolledBack — number of products whose prices were restored

After rollback the proposals' status changes to "rolled_back".  The products
return to the prices they had immediately before the batch was approved.`,
    {
      batchId: z
        .string()
        .min(1)
        .describe(
          'The batchId returned by haszno_proposals_approve. ' +
            'Example: "b-1234abcd". ' +
            'Use haszno_proposals_list to find the batchId of approved proposals.',
        ),
      confirm: z
        .boolean()
        .describe('Must be true to proceed. Safety gate — prevents accidental writes.'),
    },
    { destructiveHint: true, idempotentHint: true },
    async (args) => {
      const gate = requireConfirm(args.confirm)
      if (gate) return gate

      try {
        const result = await client.proposals.rollback({ batchId: args.batchId })
        return ok({
          rolledBack: result.rolledBack,
          note: `${result.rolledBack} product price(s) restored from batch "${args.batchId}".`,
        })
      } catch (e) {
        return handleApiError(e, 'haszno_proposals_rollback')
      }
    },
  )
}
